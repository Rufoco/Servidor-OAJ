def ok(m): print("  [OK]  " + m)
def aviso(m): print("  [!!]  " + m)
def rd(p): return open(p, "rb").read().decode("utf-8", errors="surrogateescape")
def wr(p, t): open(p, "wb").write(t.encode("utf-8", errors="surrogateescape"))
def backup(p):
    b = p + ".bak"
    if not os.path.exists(b):
        shutil.copy(p, b); ok("Copia de seguridad: " + os.path.basename(b))

def main():
    base = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.abspath(__file__)))
